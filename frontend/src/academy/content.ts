// Stable option order: the thoughtful action must not always be option A.
// IDs, rather than display positions, form the persisted learning path.
export const scenes: Scene[] = authoredScenes.map((scene, index) => ({
  ...scene,
  nodes: scene.nodes.map((node, nodeIndex) => {
    const offset = (index + nodeIndex) % node.choices.length;
    return {
      ...node,
      choices: [
        ...node.choices.slice(offset),
        ...node.choices.slice(0, offset),
      ],
    };
  }),
}));
